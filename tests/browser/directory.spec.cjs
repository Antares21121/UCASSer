const {test,expect}=require('@playwright/test');
const fs=require('fs');
const {login}=require('./helpers.cjs');

test('native directory forms persist revisions and handle feedback',async({page})=>{
  test.setTimeout(120000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await login(page,'phase0_admin',fs.readFileSync('.runtime/admin-initial-password.txt','utf8').trim());
  await page.goto('/resources');
  await expect(page.getByRole('heading',{name:'资料分类目录',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'新增资料链接',exact:true}).click();
  const modal=page.locator('.Campus-directoryModal'),name='【示例】浏览器目录 '+Date.now();
  await modal.getByRole('combobox',{name:'所属课程或校外类别',exact:true}).selectOption({label:'校外资料 / 四六级'});
  await modal.getByLabel('资料名称',{exact:true}).fill(name);
  await modal.getByLabel('访问链接',{exact:true}).fill('https://cet.neea.edu.cn/');
  await modal.getByLabel('资料说明',{exact:true}).fill('开发验收：公开来源链接。');
  await modal.getByRole('button',{name:'保存',exact:true}).click();
  await expect(modal).toHaveCount(0);
  const card=page.locator('.Campus-directoryCard').filter({hasText:name});
  await expect(card).toBeVisible();
  await card.getByRole('button',{name:'修改',exact:true}).click();
  await modal.getByLabel('资料说明',{exact:true}).fill('开发验收：已核对官方原始来源。');
  await modal.getByLabel('修订原因',{exact:true}).fill('核对公开来源与说明');
  await modal.getByRole('button',{name:'保存',exact:true}).click();
  await expect(modal).toHaveCount(0);
  await expect(card).toContainText('已核对官方原始来源');
  await card.getByRole('button',{name:'修订记录',exact:true}).click();
  const history=page.locator('.CampusRecordActionModal');
  await expect(history).toContainText('核对公开来源与说明');
  await expect(history.locator('del').filter({hasText:'公开来源链接'})).toHaveCount(1);
  await history.getByRole('button',{name:'关闭',exact:true}).click();
  await card.getByRole('button',{name:'反馈问题',exact:true}).click();
  await modal.getByLabel('问题说明',{exact:true}).fill('开发验收：请确认页面说明是否准确。');
  await modal.getByRole('button',{name:'提交反馈',exact:true}).click();
  await expect(modal).toHaveCount(0);
  await page.getByRole('button',{name:'查看待处理反馈',exact:true}).click();
  const report=page.locator('.Campus-directoryReport').filter({hasText:name});
  await expect(report).toBeVisible();
  await report.getByRole('button',{name:'标记已处理',exact:true}).click();
  await expect(report).toHaveCount(0);
  await page.reload();
  await expect(card).toContainText('已核对官方原始来源');
  expect(errors).toEqual([]);
});
